import { test, expect } from '@playwright/test'

test('raw CRM collection, owner settings, conversion and responsive editor',async({page})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/register')
  await page.getByLabel('Username',{exact:false}).fill(`rawui${Date.now()}`)
  await page.getByLabel('Password',{exact:true}).fill('Testing-password-2026')
  await page.getByLabel('Konfirmasi password',{exact:true}).fill('Testing-password-2026')
  await page.getByRole('button',{name:'Buat akun Utusan'}).click()
  await expect(page.getByRole('heading',{name:/Halo,/})).toBeVisible()
  await page.goto('/crm')
  await expect(page.getByRole('heading',{name:'CRM • Raw Message',exact:true})).toBeVisible()
  await page.getByLabel('Owner tambahan',{exact:false}).fill('6281776348790')
  await page.getByRole('button',{name:'Simpan akses owner'}).click()
  await expect(page.getByRole('status')).toContainText('Akses owner CRM disimpan')
  await page.getByLabel('Nama pesan').fill('Contoh CRM')
  await page.getByLabel('Raw message JSON',{exact:false}).fill('{"conversation":"Raw pesan contoh"}')
  await page.getByRole('button',{name:'Simpan ke DB',exact:true}).click()
  await expect(page.locator('.crm-items')).toContainText('Contoh CRM')
  await page.getByRole('button',{name:'Tambah ke Aksi',exact:true}).click()
  await page.getByLabel('Tampilkan',{exact:false}).selectOption('action')
  await expect(page.locator('.crm-items')).toContainText('Aksi')
  await page.reload()
  await expect(page.getByLabel('Owner tambahan',{exact:false})).toHaveValue('6281776348790')
  await page.locator('.crm-item').filter({hasText:'Aksi'}).click()
  await expect(page.getByLabel('Raw message JSON',{exact:false})).toHaveValue('{\n  "conversation": "Raw pesan contoh"\n}')
  await page.route('**/api/web/devices',route=>route.fulfill({json:{devices:[{phone:'628123456789',number:'628123456789',online:true,pairing:false}]}}))
  await page.reload()
  await page.locator('.crm-item').filter({hasText:'Aksi'}).click()
  let sent:Record<string,unknown>|null=null
  await page.route('**/api/web/crm/items/*/run',async route=>{sent=route.request().postDataJSON();await route.fulfill({json:{success:true,status:'sent'}})})
  await page.getByLabel('Tujuan',{exact:false}).fill('120363123456789@g.us')
  await page.getByRole('button',{name:'Jalankan',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('Raw message terkirim')
  expect(sent).toMatchObject({phone:'628123456789',to:'120363123456789@g.us'})
  await page.getByLabel('Raw message JSON',{exact:false}).fill('{"conversation":"Berubah"}')
  await expect(page.getByRole('button',{name:'Jalankan',exact:true})).toBeDisabled()
  await page.route('**/api/web/convert-jid',route=>route.fulfill({json:{success:true,result:'123456789123@lid',direction:'PN → LID'}}))
  await page.getByLabel('JID / nomor untuk konversi').fill('6281776348790@s.whatsapp.net')
  await page.getByRole('button',{name:'Konversi',exact:true}).click()
  await expect(page.locator('.crm-conversion')).toContainText('123456789123@lid')
  await page.setViewportSize({width:390,height:844})
  await page.evaluate(()=>window.scrollTo(0,0))
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.screenshot({path:'test-results/crm-mobile.png',fullPage:true})
  await page.getByRole('button',{name:'Aktifkan dark mode'}).click()
  await page.screenshot({path:'test-results/crm-mobile-dark.png',fullPage:true})
  await page.getByRole('button',{name:'Hapus',exact:true}).click()
  await page.getByRole('button',{name:'Hapus dari DB',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('Raw message dihapus')
  expect(errors).toEqual([])
})
